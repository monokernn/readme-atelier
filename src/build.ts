import { renderCard, renderCombined, type Card } from './card.js';
import { configToYaml, encodeConfig, makeCtx } from './config.js';
import { THEMES } from './themes/index.js';
import type { Theme } from './themes/shared.js';
import type { AtelierConfig, Ctx, Profile, Scheme } from './types.js';
import { socialIcon } from './icons.js';
import { esc } from './util.js';

export const REPO_URL = 'https://github.com/monokern/readme-atelier';
export const ACTION_REF = 'monokern/readme-atelier@v1';
export const ASSET_DIR = 'atelier';
export const START = '<!-- readme-atelier:start -->';
export const END = '<!-- readme-atelier:end -->';

export type CardName =
  | 'header' | 'stats' | 'languages' | 'activity' | 'stack' | 'footer'
  | `repo-${number}` | `social-${string}`;

function featured(ctx: Ctx) {
  return ctx.p.repos.slice(0, 4);
}

/** Render one named card as a Card object (not yet serialised). */
export function cardFor(theme: Theme, ctx: Ctx, name: CardName): Card | null {
  if (name === 'header') return theme.header(ctx);
  if (name === 'stats') return theme.stats(ctx);
  if (name === 'languages') return theme.languages(ctx);
  if (name === 'activity') return theme.activity(ctx);
  if (name === 'stack') return ctx.c.stack?.length ? theme.stack(ctx) : null;
  if (name === 'footer') return theme.footer(ctx);
  if (name.startsWith('repo-')) {
    const r = featured(ctx)[parseInt(name.slice(5), 10) - 1];
    return r ? theme.repo(ctx, r) : null;
  }
  if (name.startsWith('social-')) {
    const s = ctx.socials.find((x) => x.kind === name.slice(7));
    return s ? theme.social(ctx, s) : null;
  }
  return null;
}

/** Serialise one card to SVG text. Used by the hosted image endpoint. */
export async function renderNamedCard(profile: Profile, cfg: AtelierConfig, name: CardName, scheme?: Scheme): Promise<string | null> {
  const theme = THEMES[cfg.theme];
  const sch = scheme && theme.schemes.includes(scheme) ? scheme : theme.schemes[0];
  const card = cardFor(theme, makeCtx(profile, cfg, theme.accent, sch), name);
  return card ? renderCard(card, 'ra') : null;
}

/** Where images live: files in the repo, or the hosted endpoint. */
export type ImageSource =
  | { kind: 'files'; dir?: string }
  | { kind: 'hosted'; base: string };

function imgUrl(src: ImageSource, cfg: AtelierConfig, name: string, scheme: Scheme, primary: Scheme): string {
  if (src.kind === 'files') return `./${src.dir ?? ASSET_DIR}/${name}${scheme === primary ? '' : '-' + scheme}.svg`;
  const q = `cfg=${encodeConfig(cfg)}` + (scheme === primary ? '' : `&scheme=${scheme}`);
  return `${src.base.replace(/\/$/, '')}/api/card/${name}.svg?${q}`;
}

function img(theme: Theme, src: ImageSource, cfg: AtelierConfig, name: string, attrs: string, alt: string) {
  const [primary, ...rest] = theme.schemes;
  const tag = `<img src="${imgUrl(src, cfg, name, primary, primary)}" ${attrs} alt="${esc(alt)}"/>`;
  if (!rest.length) return tag;
  const sources = rest
    .map((s) => `<source media="(prefers-color-scheme: ${s})" srcset="${imgUrl(src, cfg, name, s, primary)}"/>`)
    .join('');
  return `<picture>${sources}${tag}</picture>`;
}

/** The generated README block (between the start/end markers). */
export function readmeBlock(profile: Profile, cfg: AtelierConfig, src: ImageSource): string {
  const theme = THEMES[cfg.theme];
  const ctx = makeCtx(profile, cfg, theme.accent, theme.schemes[0]);
  const sections = cfg.sections ?? [];
  const out: string[] = [START, `<!-- Generated by Readme Atelier (${REPO_URL}). Edit atelier.yml instead of this block. -->`, ''];
  const I = (name: string, attrs: string, alt: string) => img(theme, src, cfg, name, attrs, alt);
  for (const s of sections) {
    if (s === 'header') out.push(`<p align="center">${I('header', 'width="100%"', ctx.name)}</p>`, '');
    if (s === 'socials' && ctx.socials.length) {
      const links = ctx.socials.map((x) => `<a href="${esc(x.url)}">${I('social-' + x.kind, 'height="36"', x.label)}</a>`);
      out.push(`<p align="center">\n  ${links.join('&nbsp;\n  ')}\n</p>`, '');
    }
    if (s === 'stats') out.push(`<p align="center">\n  ${I('stats', 'width="49%"', 'GitHub stats')}\n  ${I('languages', 'width="49%"', 'Top languages')}\n</p>`, '');
    if (s === 'activity') out.push(`<p align="center">${I('activity', 'width="100%"', 'Contribution activity')}</p>`, '');
    if (s === 'repos') {
      const repos = featured(ctx);
      if (repos.length) {
        const cells = repos.map((r, i) => `<a href="${esc(r.url)}">${I('repo-' + (i + 1), 'width="49%"', r.name)}</a>`);
        out.push(`<p align="center">\n  ${cells.join('\n  ')}\n</p>`, '');
      }
    }
    if (s === 'stack' && cfg.stack?.length) out.push(`<p align="center">${I('stack', 'width="100%"', 'Tech stack')}</p>`, '');
    if (s === 'footer') out.push(`<p align="center">${I('footer', 'width="100%"', 'Footer')}</p>`, '');
  }
  out.push(END);
  return out.join('\n');
}

/** Insert or replace the generated block inside an existing README. */
export function mergeReadme(existing: string | null, block: string): string {
  if (existing && existing.includes(START) && existing.includes(END)) {
    const a = existing.indexOf(START);
    const b = existing.indexOf(END) + END.length;
    return existing.slice(0, a) + block + existing.slice(b);
  }
  return block + '\n';
}

/** Every card, for every scheme the theme supports, as SVG files keyed by repo path. */
export async function buildAssets(profile: Profile, cfg: AtelierConfig, dir = ASSET_DIR): Promise<Record<string, string>> {
  const theme = THEMES[cfg.theme];
  const names: CardName[] = ['header', 'stats', 'languages', 'activity', 'stack', 'footer'];
  const ctx0 = makeCtx(profile, cfg, theme.accent, theme.schemes[0]);
  featured(ctx0).forEach((_, i) => names.push(`repo-${i + 1}`));
  ctx0.socials.forEach((s) => names.push(`social-${s.kind}`));
  const files: Record<string, string> = {};
  for (const scheme of theme.schemes) {
    const ctx = makeCtx(profile, cfg, theme.accent, scheme);
    const suffix = scheme === theme.schemes[0] ? '' : '-' + scheme;
    await Promise.all(
      names.map(async (n) => {
        const card = cardFor(theme, ctx, n);
        if (card) files[`${dir}/${n}${suffix}.svg`] = await renderCard(card, 'ra');
      }),
    );
  }
  return files;
}

export function workflowYaml(): string {
  return `# Rebuilds your profile README every day and whenever atelier.yml changes.
name: Readme Atelier

on:
  push:
    paths: ['atelier.yml', '.github/workflows/readme-atelier.yml']
  schedule:
    - cron: '23 4 * * *'
  workflow_dispatch:

permissions:
  contents: write

jobs:
  build:
    # never runs inside the template itself, only in your copy
    if: github.repository != 'monokern/readme-atelier-template'
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: ${ACTION_REF}
`;
}

