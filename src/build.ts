/** Everything needed for the ZIP / local install: README, assets, config, workflow, guide. */
export async function buildRepoFiles(profile: Profile, cfg: AtelierConfig): Promise<Record<string, string>> {
  const assets = await buildAssets(profile, cfg);
  return {
    'README.md': mergeReadme(null, readmeBlock(profile, cfg, { kind: 'files' })),
    'atelier.yml': configToYaml(cfg),
    '.github/workflows/readme-atelier.yml': workflowYaml(),
    'INSTALL.md': installGuide(cfg),
    ...assets,
  };
}

/** Single-file variant: one combined SVG + a README that points at it. */
export async function buildSingleFile(profile: Profile, cfg: AtelierConfig): Promise<{ svg: string; readme: string }> {
  const theme = THEMES[cfg.theme];
  const ctx = makeCtx(profile, cfg, theme.accent, theme.schemes[0]);
  const sec = cfg.sections ?? [];
  const rows: Card[][] = [];
  const push = (...cs: (Card | null)[]) => {
    const ok = cs.filter(Boolean) as Card[];
    if (ok.length) rows.push(ok);
  };
  const repos = featured(ctx);
  for (const s of sec) {
    if (s === 'header') push(theme.header(ctx));
    if (s === 'stats') push(theme.stats(ctx), theme.languages(ctx));
    if (s === 'activity') push(theme.activity(ctx));
    if (s === 'repos') for (let i = 0; i < repos.length; i += 2) push(...repos.slice(i, i + 2).map((r) => theme.repo(ctx, r)));
    if (s === 'stack' && cfg.stack?.length) push(theme.stack(ctx));
    if (s === 'footer') push(theme.footer(ctx));
  }
  const svg = await renderCombined(rows, `${ctx.name} · GitHub profile`);
  const lines = [START, '', `<p align="center"><img src="./profile.svg" width="100%" alt="${esc(ctx.name)}"/></p>`, ''];
  if (sec.includes('socials') && ctx.socials.length) lines.push(`<p align="center">${ctx.socials.map((s) => `<a href="${esc(s.url)}">${esc(s.kind === 'website' ? s.label : socialIcon(s.kind).title)}</a>`).join(' · ')}</p>`, '');
  if (sec.includes('repos') && repos.length) lines.push(`<p align="center">${repos.map((r) => `<a href="${esc(r.url)}">${esc(r.name)}</a>`).join(' · ')}</p>`, '');
  lines.push(END);
  return { svg, readme: lines.join('\n') + '\n' };
}
