// Pre-subsets the OFL fonts used by themes into base64 WOFF2 modules.
// Subset: Basic Latin + Latin-1 + a few typographic symbols. Run: npm run fonts
import fs from 'node:fs';
import path from 'node:path';
import subsetFont from 'subset-font';

const FONTS = {
  mono400: '@fontsource/jetbrains-mono/files/jetbrains-mono-latin-400-normal.woff2',
  mono700: '@fontsource/jetbrains-mono/files/jetbrains-mono-latin-700-normal.woff2',
  unbounded400: '@fontsource/unbounded/files/unbounded-latin-400-normal.woff2',
  unbounded800: '@fontsource/unbounded/files/unbounded-latin-800-normal.woff2',
  silkscreen400: '@fontsource/silkscreen/files/silkscreen-latin-400-normal.woff2',
  pixelify400: '@fontsource/pixelify-sans/files/pixelify-sans-latin-400-normal.woff2',
  pixelify700: '@fontsource/pixelify-sans/files/pixelify-sans-latin-700-normal.woff2',
  serif400: '@fontsource/instrument-serif/files/instrument-serif-latin-400-normal.woff2',
  serif400i: '@fontsource/instrument-serif/files/instrument-serif-latin-400-italic.woff2',
  sans400: '@fontsource/instrument-sans/files/instrument-sans-latin-400-normal.woff2',
  sans600: '@fontsource/instrument-sans/files/instrument-sans-latin-600-normal.woff2',
  fraunces400: '@fontsource/fraunces/files/fraunces-latin-400-normal.woff2',
  fraunces700i: '@fontsource/fraunces/files/fraunces-latin-700-italic.woff2',
};

let text = '';
for (let c = 0x20; c <= 0x7e; c++) text += String.fromCharCode(c);
for (let c = 0xa0; c <= 0xff; c++) text += String.fromCharCode(c);
text += '—–·•…→←↑↓★☆✦✧●○◆◇■□▲▶►▸⌁⑂“”‘’№✓✕×';

const out = ['// Generated by scripts/build-fonts.mjs — do not edit.', '// Fonts: SIL Open Font License 1.1 (see fonts/LICENSES.md).', ''];
let total = 0;
for (const [key, rel] of Object.entries(FONTS)) {
  const src = fs.readFileSync(path.join('node_modules', rel));
  const sub = await subsetFont(src, text, { targetFormat: 'woff2' });
  total += sub.length;
  out.push(`export const ${key} = '${sub.toString('base64')}';`);
  console.log(key.padEnd(14), (src.length / 1024).toFixed(1) + 'KB ->', (sub.length / 1024).toFixed(1) + 'KB');
}
fs.writeFileSync('src/fonts/data.ts', out.join('\n') + '\n');
console.log('total', (total / 1024).toFixed(1) + 'KB');
